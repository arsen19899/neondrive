package com.neondrive.launcher.voice

import android.content.Context

/**
 * Что вернуло распознавание.
 *
 * [partial] — промежуточная гипотеза: движок ещё слушает, но уже показывает, что
 * разобрал. За рулём это не украшение: человек должен видеть, что его слышат, до
 * того как фраза закончится, иначе он начинает повторять её громче.
 */
data class SpeechResult(val text: String, val partial: Boolean)

/**
 * Зачем открыт микрофон прямо сейчас.
 *
 * Разделение важно не для красоты, а для нагрузки на процессор: ожидание
 * ключевого слова может идти часами и потому должно быть максимально дешёвым,
 * а разбор команды длится секунды и может позволить себе полную модель языка.
 * См. [VoskEngine.startWakeWord] против [VoskEngine.startCommand].
 */
enum class ListenPurpose { WAKE_WORD, COMMAND }

/**
 * Общий интерфейс к распознавателю речи.
 *
 * Две реализации под две разные реальности головных устройств:
 *
 *  • [VoskEngine] — офлайн, без Google-сервисов, умеет непрерывно ждать слово
 *    «Елисей». Требует скачанной модели на устройстве;
 *  • [SystemSpeechEngine] — системный `android.speech.SpeechRecognizer`. Ничего
 *    скачивать не нужно, но на ГУ без сервисов Google распознавателя в системе
 *    нет вовсе, и непрерывное ожидание ключевого слова через него не сделать.
 *
 * [VoiceAssistant] держит оба и выбирает доступный, поэтому ни один из них не
 * обязан работать: если не работает ни один, голосовое управление честно
 * сообщает об этом в настройках, а всё остальное в оболочке живёт как раньше.
 */
interface SpeechEngine {

    /** Готов ли движок в принципе (библиотека на месте, модель загружена, сервис в системе есть). */
    fun isAvailable(context: Context): Boolean

    /** Человеческое объяснение, почему движок недоступен. Пусто — доступен. */
    fun unavailableReason(context: Context): String

    /**
     * Начать слушать.
     *
     * [onResult] вызывается и на промежуточных гипотезах (`partial = true`), и на
     * окончательной (`partial = false`). Окончательный результат для
     * [ListenPurpose.COMMAND] означает, что движок закончил и больше слушать не
     * будет — перезапуск на совести вызывающего.
     */
    fun start(
        context: Context,
        purpose: ListenPurpose,
        onResult: (SpeechResult) -> Unit,
        onError: (String) -> Unit
    )

    /** Остановить прослушивание и отпустить микрофон. */
    fun stop()

    /** Отпустить всё, включая выгрузку модели из памяти. */
    fun release()
}
